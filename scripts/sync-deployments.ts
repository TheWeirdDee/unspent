// Single source of truth: deployments.json + the Foundry artifact.
// Writes the ABI and network config into BOTH the primary app and the independent
// recovery client, so the recovery client never imports anything from the primary app.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("../", import.meta.url).pathname;
const artifact = JSON.parse(readFileSync(`${root}contracts/out/UnspentVault.sol/UnspentVault.json`, "utf8"));
const deployments = JSON.parse(readFileSync(`${root}deployments.json`, "utf8"));

const abiSrc = `// GENERATED by scripts/sync-deployments.ts from contracts/out. Do not edit.\nexport const unspentVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
const depSrc = `// GENERATED by scripts/sync-deployments.ts from deployments.json. Do not edit.\nexport const deployments = ${JSON.stringify(deployments, null, 2)} as const;\nexport type NetworkKey = keyof typeof deployments;\n`;

for (const dir of ["src/contracts", "recovery/src/contracts"]) {
  mkdirSync(`${root}${dir}`, { recursive: true });
  writeFileSync(`${root}${dir}/abi.ts`, abiSrc);
  writeFileSync(`${root}${dir}/deployments.ts`, depSrc);
}
console.log("synced ABI + deployments to src/contracts and recovery/src/contracts");
